// Shared header block for printable pages: parties, lock, hash, QR.
import type { Member } from "@/lib/tenancies";

const fmt = (iso: string | null) => (iso ? new Date(iso).toLocaleString("en-IN", { dateStyle: "medium", timeStyle: "short" }) : "—");

export function PrintReportMeta({ label, lockedAt, selfAttested, hash, qr, verifyUrl }: {
  label: string; lockedAt: string | null; selfAttested: boolean; hash: string | null; qr: string; verifyUrl: string;
}) {
  return (
    <div className="print-avoid flex gap-3 rounded-lg border p-3">
      {/* eslint-disable-next-line @next/next/no-img-element -- data URL QR */}
      <img src={qr} alt={`QR code: ${verifyUrl}`} className="size-24 shrink-0" />
      <div className="min-w-0 space-y-1 text-xs">
        <p className="font-semibold">{label}</p>
        <p>Locked: {fmt(lockedAt)}{selfAttested && <span className="ml-1 rounded bg-yellow-100 px-1 text-yellow-900">Self-attested</span>}</p>
        <p className="break-all font-mono">{hash ?? "Not locked — no final hash"}</p>
        <p className="break-all text-muted-foreground">Verify: {verifyUrl}</p>
      </div>
    </div>
  );
}

export function PrintParties({ members }: { members: Member[] }) {
  return (
    <p className="text-sm">
      {(["OWNER", "TENANT"] as const).map((r) => {
        const m = members.find((x) => x.role === r);
        return <span key={r} className="mr-4">{r === "OWNER" ? "Owner" : "Tenant"}: <strong>{m?.display_name ?? "Not joined"}</strong></span>;
      })}
    </p>
  );
}

export const PrintFooter = () => (
  <p className="mt-6 border-t pt-2 text-center text-xs text-muted-foreground">Evidence record generated by MoveProof. Not a legal contract.</p>
);
export { fmt as fmtPrintDate };
